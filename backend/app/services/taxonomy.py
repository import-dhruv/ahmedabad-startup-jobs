def slugify(value: str) -> str:
    # Keep "+" and "#" so that skills like "C++" and "C#" remain distinct.
    value = re.sub(r"[^a-zA-Z0-9+#]+", "-", value).strip("-").lower()
    return value[:80] or "unknown"


def skill_categories() -> list[tuple[str, str, bool]]:
    return [(name, cat, is_ai) for name, (cat, is_ai) in SKILL_CATALOG.items()]
